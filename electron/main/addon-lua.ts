/**
 * Generador puro (sin Electron) de los archivos del addon de datos
 * `GoblinCompanion_Data`, que el addon principal `GoblinCompanion`
 * (repo aparte) lee como la global `GoblinCompanionData`.
 */

export const DATA_ADDON_NAME = 'GoblinCompanion_Data'
export const MAIN_ADDON_NAME = 'GoblinCompanion'
export const DATA_SCHEMA_VERSION = 1
export const DEFAULT_INTERFACE_VERSION = '120105'

export interface BuyListItem {
  id: number
  name: string
  need: number
  target: number
  owned: number
  buy_price: number
  sell_realm: string
  tsm: string
}

export interface BuyListRealm {
  name: string
  slug: string
  tsm_search: string
  items: BuyListItem[]
}

export interface BuyListPayload {
  generated_at?: string
  realms: BuyListRealm[]
}

/** Escapa un string como literal Lua entre comillas dobles. */
export function luaString(value: unknown): string {
  const s = String(value ?? '')
  let out = '"'
  for (const ch of s) {
    const code = ch.codePointAt(0) ?? 0
    if (ch === '\\') out += '\\\\'
    else if (ch === '"') out += '\\"'
    else if (ch === '\n') out += '\\n'
    else if (ch === '\r') out += '\\r'
    else if (ch === '\t') out += '\\t'
    else if (code < 0x20 || code === 0x7f) out += `\\${String(code).padStart(3, '0')}`
    else out += ch
  }
  return out + '"'
}

function luaNumber(value: unknown, fallback = 0): string {
  const n = Number(value)
  return Number.isFinite(n) ? String(n) : String(fallback)
}

function epochSeconds(iso: string | undefined): number {
  const ms = iso ? Date.parse(iso) : NaN
  return Number.isFinite(ms) ? Math.floor(ms / 1000) : 0
}

export function buildDataLua(payload: BuyListPayload, hash: string, writtenAtIso: string): string {
  const lines: string[] = []
  lines.push('-- Generated by Goblin Companion. DO NOT EDIT: this file is overwritten on every sync.')
  lines.push('GoblinCompanionData = {')
  lines.push(`  schema = ${DATA_SCHEMA_VERSION},`)
  lines.push(`  hash = ${luaString(hash)},`)
  lines.push(`  generated_at = ${luaString(payload.generated_at ?? '')},`)
  lines.push(`  written_at = ${luaString(writtenAtIso)},`)
  // Epoch UTC en segundos: el addon lo compara con time() para avisar de datos viejos.
  lines.push(`  written_ts = ${epochSeconds(writtenAtIso)},`)
  lines.push(`  generated_ts = ${epochSeconds(payload.generated_at)},`)
  lines.push('  realms = {')
  for (const realm of payload.realms) {
    lines.push('    {')
    lines.push(`      name = ${luaString(realm.name)},`)
    lines.push(`      slug = ${luaString(realm.slug)},`)
    lines.push(`      tsm_search = ${luaString(realm.tsm_search)},`)
    lines.push('      items = {')
    for (const it of realm.items) {
      lines.push(
        '        { ' +
          `id = ${luaNumber(it.id)}, ` +
          `name = ${luaString(it.name)}, ` +
          `need = ${luaNumber(it.need)}, ` +
          `target = ${luaNumber(it.target)}, ` +
          `owned = ${luaNumber(it.owned)}, ` +
          `buy_price = ${luaNumber(it.buy_price)}, ` +
          `sell_realm = ${luaString(it.sell_realm)}, ` +
          `tsm = ${luaString(it.tsm)} },`
      )
    }
    lines.push('      },')
    lines.push('    },')
  }
  lines.push('  },')
  lines.push('}')
  lines.push('')
  return lines.join('\n')
}

export function buildDataToc(interfaceVersion: string, hash: string): string {
  return [
    `## Interface: ${interfaceVersion}`,
    '## Title: Goblin Companion Data',
    '## Notes: Generated by the Goblin Companion desktop app. Do not edit.',
    `## Version: ${DATA_SCHEMA_VERSION}`,
    `## X-DataHash: ${hash}`,
    '',
    'Data.lua',
    ''
  ].join('\n')
}

/** Primer número de `## Interface:` de un .toc (ej. "120105, 50504" -> "120105"). */
export function parseInterfaceVersion(tocText: string): string | null {
  const m = tocText.match(/^##\s*Interface\s*:\s*(\d+)/im)
  return m ? m[1] : null
}

/**
 * Deriva `...\_retail_\Interface\AddOns` desde la ruta SavedVariables
 * (`...\_retail_\WTF\Account\<ACCT>\SavedVariables`). Devuelve '' si no encuentra `WTF`.
 */
export function deriveAddonsPath(savedVariablesPath: string): string {
  const normalized = savedVariablesPath.trim().replace(/[\\/]+/g, '\\')
  const parts = normalized.split('\\')
  const idx = parts.findIndex((p) => p.toLowerCase() === 'wtf')
  if (idx <= 0) return ''
  return [...parts.slice(0, idx), 'Interface', 'AddOns'].join('\\')
}
